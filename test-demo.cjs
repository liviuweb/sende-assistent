// Kompletter Durchlauf im Demo-Modus (simuliertes OBS), mit Bildschirmfotos
const { chromium } = require('playwright');
const path = require('path');
const out = require('os').tmpdir(); // Testbilder landen außerhalb des Repos
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: Number(process.env.W || 1440), height: Number(process.env.H || 900) } });
  const fehler = [];
  p.on('pageerror', (e) => fehler.push('pageerror: ' + e.message));
  p.on('console', (m) => m.type() === 'error' && fehler.push('console: ' + m.text()));
  await p.goto('file://' + path.join(__dirname, 'index.html'));
  const shot = (n) => p.screenshot({ path: `${out}/${process.env.PFX || ''}${n}.png` });
  await shot('0_start');
  await p.click('#demoStart');
  await p.waitForSelector('section[data-s="1"].aktiv');
  await shot('1_geraete');
  await p.click('#quellenAnlegen');
  await p.waitForFunction(() => !document.querySelector('#weiter1').disabled);
  await p.waitForTimeout(400); await shot('1b_quellen');
  await p.click('#weiter1');
  const btns = await p.$$('#tonListe button');
  await btns[0].click(); await p.waitForTimeout(2500); await shot('2_ton_messen');
  await btns[1].click();
  await p.waitForFunction(() => document.querySelectorAll('#tonListe .vergleich').length === 2, null, { timeout: 30000 });
  await shot('2b_ton_fertig');
  console.log('Ton:', await p.$$eval('#tonListe .vergleich', (v) => v.map((x) => x.textContent.replace(/\s+/g, ' ').trim())));
  await p.click('#weiter2');
  await p.click('#szenenBauen');
  await p.waitForFunction(() => !document.querySelector('#weiter3').disabled);
  await p.waitForTimeout(300); await shot('3_szenen');
  await p.click('#weiter3');
  await p.click('#logoEinfuegen');
  await p.waitForSelector('#kollision .warnbox, #kollision .okbox');
  await p.waitForTimeout(300); await shot('4_kollision');
  console.log('Kollision:', (await p.textContent('#kollision')).replace(/\s+/g, ' ').trim());
  await p.click('#verschieben');
  await p.waitForSelector('#kollision .okbox');
  console.log('Nachher:', (await p.textContent('#kollision')).trim());
  await shot('4b_frei');
  await p.click('#weiter4');
  await p.click('#pruefen');
  await p.waitForFunction(() => document.querySelectorAll('#ampel .p').length > 0, null, { timeout: 20000 });
  console.log('Live gesperrt ohne Key:', await p.isDisabled('#liveGehen'));
  await shot('5_startcheck_rot');
  await p.click('#demoKey'); await p.click('#pruefen');
  await p.waitForFunction(() => !document.querySelector('#liveGehen').disabled, null, { timeout: 20000 });
  await p.click('#fMute');
  await p.waitForFunction(() => document.querySelector('#liveGehen').disabled && document.querySelector('#ampel .rot'), null, { timeout: 20000 });
  await p.waitForTimeout(300); await shot('5b_fehler');
  console.log('Mit stummem Mikro gesperrt:', await p.isDisabled('#liveGehen'));
  await p.click('#ampel .rot button');
  await p.waitForFunction(() => !document.querySelector('#liveGehen').disabled, null, { timeout: 20000 });
  console.log('Ampel:', await p.$$eval('#ampel .p', (v) => v.map((x) => x.className.split(' ')[1] + ' ' + x.querySelector('b').textContent).join(' | ')));
  await p.click('#liveGehen');
  await p.waitForSelector('section[data-s="6"].aktiv');
  await p.keyboard.press('3'); await p.waitForTimeout(500);
  await p.keyboard.press('5'); await p.waitForTimeout(700);
  await shot('6_live');
  await p.click('.seg button[data-u="auto"]'); await p.keyboard.press('1'); await p.waitForTimeout(120); await shot('6b_ueberblendung');
  await p.waitForTimeout(1500);
  await p.click('#beenden');
  await p.waitForSelector('section[data-s="7"].aktiv'); await shot('7_ergebnis');
  console.log('Zahlen:', await p.$$eval('.zahl', (v) => v.map((x) => x.textContent.trim()).join(' | ')));
  console.log('Fehler:', fehler.length ? fehler : 'keine');
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
